CREATE OR REPLACE FUNCTION apex_admin_invoice_line_totals()
RETURNS TRIGGER AS $$
DECLARE
    v_subtotal NUMERIC(7,2);
    v_discount NUMERIC(7,2);
BEGIN
    SELECT fac_subtotal, COALESCE(fac_descuento, 0)
    INTO v_subtotal, v_discount
    FROM facturas
    WHERE id_factura = NEW.id_factura
    FOR UPDATE;

    v_subtotal := COALESCE(v_subtotal, 0) + NEW.pxf_subtotal;
    UPDATE facturas
    SET fac_subtotal = v_subtotal,
        fac_iva = ROUND(GREATEST(v_subtotal - v_discount, 0) * 0.15, 2),
        fac_total = ROUND(GREATEST(v_subtotal - v_discount, 0) * 1.15, 2)
    WHERE id_factura = NEW.id_factura;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_apex_admin_invoice_line_totals
AFTER INSERT ON proxfac
FOR EACH ROW EXECUTE FUNCTION apex_admin_invoice_line_totals();

CREATE OR REPLACE FUNCTION apex_admin_confirm_invoice()
RETURNS TRIGGER AS $$
DECLARE
    v_line RECORD;
    v_delivery_id CHAR(15);
    v_product_count INTEGER;
BEGIN
    IF OLD.estado_fac = 'ABI' AND NEW.estado_fac = 'APR' THEN
        PERFORM pg_advisory_xact_lock(hashtextextended('apex-admin-inventory', 0));
        PERFORM p.id_producto
        FROM productos p
        JOIN proxfac d ON d.id_producto = p.id_producto
        WHERE d.id_factura = NEW.id_factura
        ORDER BY p.id_producto
        FOR UPDATE OF p;

        FOR v_line IN
            SELECT p.id_producto, p.pro_saldo_final, SUM(d.pxf_cantidad)::INTEGER AS quantity
            FROM productos p
            JOIN proxfac d ON d.id_producto = p.id_producto
            WHERE d.id_factura = NEW.id_factura
            GROUP BY p.id_producto, p.pro_saldo_final
            ORDER BY p.id_producto
        LOOP
            IF v_line.pro_saldo_final < v_line.quantity THEN
                RAISE EXCEPTION 'Insufficient stock for product %', trim(v_line.id_producto)
                    USING ERRCODE = 'check_violation';
            END IF;

            UPDATE productos
            SET pro_qty_egresos = pro_qty_egresos + v_line.quantity,
                pro_saldo_final = pro_saldo_final - v_line.quantity
            WHERE id_producto = v_line.id_producto;
        END LOOP;

        SELECT COUNT(*) INTO v_product_count
        FROM proxfac WHERE id_factura = NEW.id_factura;
        v_delivery_id := ('ENT' || SUBSTRING(MD5(NEW.id_factura) FROM 1 FOR 12))::CHAR(15);
        INSERT INTO entregas
            (id_entrega, id_factura, ent_descripcion, ent_fechahora, ent_num_produc, estado_ent)
        VALUES
            (v_delivery_id, NEW.id_factura, 'Despacho por venta aprobada',
             CURRENT_TIMESTAMP, v_product_count, 'PEN');

        INSERT INTO proxent
            (id_entrega, id_producto, pxe_cantidad, pxe_qty_entregada, pxe_motivo, estado_pxent)
        SELECT v_delivery_id, id_producto, pxf_cantidad, 0, NULL, 'ACT'
        FROM proxfac
        WHERE id_factura = NEW.id_factura;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_apex_admin_confirm_invoice
AFTER UPDATE OF estado_fac ON facturas
FOR EACH ROW EXECUTE FUNCTION apex_admin_confirm_invoice();

CREATE OR REPLACE FUNCTION apex_admin_confirm_receipt()
RETURNS TRIGGER AS $$
DECLARE
    v_line RECORD;
BEGIN
    IF OLD.estado_rec = 'PEN' AND NEW.estado_rec = 'REC' THEN
        PERFORM pg_advisory_xact_lock(hashtextextended('apex-admin-inventory', 0));
        PERFORM p.id_producto
        FROM productos p
        JOIN proxrec r ON r.id_producto = p.id_producto
        WHERE r.id_recibo = NEW.id_recibo
        ORDER BY p.id_producto
        FOR UPDATE OF p;

        FOR v_line IN
            SELECT p.id_producto, SUM(r.pxr_qty_recibida)::INTEGER AS quantity
            FROM productos p
            JOIN proxrec r ON r.id_producto = p.id_producto
            WHERE r.id_recibo = NEW.id_recibo
            GROUP BY p.id_producto
            ORDER BY p.id_producto
        LOOP
            UPDATE productos
            SET pro_qty_ingresos = pro_qty_ingresos + v_line.quantity,
                pro_saldo_final = pro_saldo_final + v_line.quantity
            WHERE id_producto = v_line.id_producto;
        END LOOP;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_apex_admin_confirm_receipt
AFTER UPDATE OF estado_rec ON recepciones
FOR EACH ROW EXECUTE FUNCTION apex_admin_confirm_receipt();

CREATE OR REPLACE FUNCTION apex_admin_confirm_adjustment()
RETURNS TRIGGER AS $$
DECLARE
    v_line RECORD;
    v_new_stock INTEGER;
BEGIN
    IF OLD.estado_aju = 'ABI' AND NEW.estado_aju = 'APR' THEN
        PERFORM pg_advisory_xact_lock(hashtextextended('apex-admin-inventory', 0));
        PERFORM p.id_producto
        FROM productos p
        JOIN proxaju a ON a.id_producto = p.id_producto
        WHERE a.id_ajuste = NEW.id_ajuste
        ORDER BY p.id_producto
        FOR UPDATE OF p;

        FOR v_line IN
            SELECT p.id_producto, p.pro_saldo_final, a.pxa_cantidad AS delta
            FROM productos p
            JOIN proxaju a ON a.id_producto = p.id_producto
            WHERE a.id_ajuste = NEW.id_ajuste
            ORDER BY p.id_producto
        LOOP
            v_new_stock := v_line.pro_saldo_final + v_line.delta;
            IF v_new_stock < 0 THEN
                RAISE EXCEPTION 'Inventory adjustment would make stock negative for product %',
                    trim(v_line.id_producto) USING ERRCODE = 'check_violation';
            END IF;

            UPDATE productos
            SET pro_qty_ajustes = pro_qty_ajustes + v_line.delta,
                pro_saldo_final = v_new_stock
            WHERE id_producto = v_line.id_producto;
        END LOOP;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_apex_admin_confirm_adjustment
AFTER UPDATE OF estado_aju ON ajustes
FOR EACH ROW EXECUTE FUNCTION apex_admin_confirm_adjustment();

