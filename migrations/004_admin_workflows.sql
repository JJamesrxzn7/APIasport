CREATE TABLE apex_inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id CHAR(10) NOT NULL REFERENCES productos(id_producto),
    actor_id CHAR(16) NOT NULL REFERENCES usuarios(id_usuario),
    quantity_delta INTEGER NOT NULL CHECK (quantity_delta <> 0),
    reason VARCHAR(32) NOT NULL CHECK (
        reason IN ('purchase_receipt', 'inventory_adjustment', 'admin_sale')
    ),
    reference_id CHAR(15) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX apex_inventory_movements_product_date_idx
    ON apex_inventory_movements(product_id, created_at DESC);

