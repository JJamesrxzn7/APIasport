INSERT INTO rolesxpermisos (id_rol, id_permiso, estado_rxp)
SELECT r.id_rol, p.id_permiso, 'ACT'
FROM roles r
CROSS JOIN permisos p
WHERE lower(trim(r.rol_nombre)) IN ('admin', 'administrador', 'superadministrador')
  AND p.prm_descripcion = 'API administration permission'
ON CONFLICT (id_rol, id_permiso) DO UPDATE SET estado_rxp = 'ACT';

