-- Version 001. Apply manually after the supplied table and constraints scripts.
-- This migration is PostgreSQL/Supabase-specific and is intentionally not run at startup.
BEGIN;

CREATE TABLE apex_sessions (
    token_hash CHAR(64) PRIMARY KEY,
    user_id CHAR(16) NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX apex_sessions_user_expiry_idx ON apex_sessions(user_id, expires_at);

-- Public storefront slugs are separate from the legacy CHAR(10) product/category keys.
-- Populate this table explicitly from the catalog mapping; no slug is truncated/generated.
CREATE TABLE apex_product_catalog (
    product_id CHAR(10) PRIMARY KEY REFERENCES productos(id_producto) ON DELETE CASCADE,
    slug VARCHAR(100) NOT NULL UNIQUE,
    category_slug VARCHAR(60) NOT NULL,
    image_url VARCHAR(255) NOT NULL,
    CONSTRAINT apex_product_slug_format CHECK (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
    CONSTRAINT apex_category_slug_format CHECK (category_slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
    CONSTRAINT apex_image_url_format CHECK (image_url ~ '^(https://[^[:space:]]+|images/[^[:space:]]+)$')
);
CREATE INDEX apex_catalog_category_idx ON apex_product_catalog(category_slug);

CREATE TABLE apex_orders (
    id CHAR(15) PRIMARY KEY,
    user_id CHAR(16) NOT NULL REFERENCES usuarios(id_usuario),
    client_id CHAR(10) NOT NULL REFERENCES clientes(id_cliente),
    idempotency_key VARCHAR(128) NOT NULL,
    status VARCHAR(32) NOT NULL CHECK (status IN ('AWAITING_DEMO_PAYMENT', 'CANCELLED')),
    payment_status VARCHAR(24) NOT NULL CHECK (payment_status IN ('NOT_PROCESSED')),
    payment_method VARCHAR(24) NOT NULL CHECK (payment_method = 'demo'),
    subtotal NUMERIC(10,2) NOT NULL CHECK (subtotal >= 0),
    delivery_fee NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
    total NUMERIC(10,2) NOT NULL CHECK (total >= 0),
    delivery_address VARCHAR(120) NOT NULL,
    delivery_city VARCHAR(60) NOT NULL,
    delivery_phone VARCHAR(20) NOT NULL,
    delivery_reference VARCHAR(120),
    delivery_method VARCHAR(16) NOT NULL CHECK (delivery_method IN ('estandar', 'express')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL DEFAULT (CURRENT_TIMESTAMP + INTERVAL '30 minutes'),
    UNIQUE (user_id, idempotency_key)
);
CREATE INDEX apex_orders_user_created_idx ON apex_orders(user_id, created_at DESC);
CREATE INDEX apex_orders_expiry_idx ON apex_orders(expires_at) WHERE status = 'AWAITING_DEMO_PAYMENT';

CREATE TABLE apex_order_lines (
    order_id CHAR(15) NOT NULL REFERENCES apex_orders(id) ON DELETE CASCADE,
    product_id CHAR(10) NOT NULL REFERENCES productos(id_producto),
    product_slug VARCHAR(100) NOT NULL,
    product_name VARCHAR(80) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(7,2) NOT NULL CHECK (unit_price >= 0),
    PRIMARY KEY (order_id, product_id)
);

-- Reservation and cancellation movements are auditable and never store payment credentials.
CREATE TABLE apex_stock_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id CHAR(15) NOT NULL REFERENCES apex_orders(id),
    product_id CHAR(10) NOT NULL REFERENCES productos(id_producto),
    quantity_delta INTEGER NOT NULL CHECK (quantity_delta <> 0),
    reason VARCHAR(32) NOT NULL CHECK (reason IN ('checkout_reservation', 'checkout_cancel', 'checkout_expiry')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX apex_stock_ledger_product_date_idx ON apex_stock_ledger(product_id, created_at DESC);

CREATE TABLE apex_inventory_policy (
    product_id CHAR(10) PRIMARY KEY REFERENCES productos(id_producto) ON DELETE CASCADE,
    minimum_stock INTEGER NOT NULL DEFAULT 0 CHECK (minimum_stock >= 0)
);

COMMIT;
