-- Version 003. Apply manually after the base schema and migrations 001 and 002.
-- Invitation tokens are stored only as SHA-256 digests and can be consumed once.
BEGIN;

CREATE TABLE apex_admin_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(50) NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    role_id CHAR(10) NOT NULL REFERENCES roles(id_rol),
    created_by CHAR(16) NOT NULL REFERENCES usuarios(id_usuario),
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX apex_admin_invitations_pending_email_uidx
    ON apex_admin_invitations (lower(email))
    WHERE used_at IS NULL AND revoked_at IS NULL;

CREATE INDEX apex_admin_invitations_expiry_idx
    ON apex_admin_invitations (expires_at)
    WHERE used_at IS NULL AND revoked_at IS NULL;

COMMIT;
